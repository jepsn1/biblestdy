#!/usr/bin/env node
/**
 * Regenerates packages/shared/src/versification-data.ts from the Paratext
 * standard versification files (SIL libpalaso, MIT — see that file's header):
 *
 *   curl -sLO https://raw.githubusercontent.com/sillsdev/libpalaso/master/SIL.Scripture/Resources/eng.vrs.txt
 *   curl -sLO https://raw.githubusercontent.com/sillsdev/libpalaso/master/SIL.Scripture/Resources/org.vrs.txt
 *   node tools/versification/build-data.mjs eng.vrs.txt org.vrs.txt
 *
 * Keeps the 66-book canon only: verse counts per chapter (eng in full, org
 * where it differs) and eng.vrs's mapping lines (English = original).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { BOOKS } from '../../packages/shared/dist/index.js'

const [engPath, orgPath] = process.argv.slice(2)
if (!engPath || !orgPath) throw new Error('usage: build-data.mjs <eng.vrs> <org.vrs>')
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../packages/shared/src/versification-data.ts')
const CANON = new Set(BOOKS.map((b) => b.id))

function counts(text) {
  const out = {}
  for (const line of text.split('\n')) {
    const parts = line.trim().split(/\s+/)
    if (!CANON.has(parts[0]) || line.includes('=') || line.startsWith('#')) continue
    out[parts[0]] = parts.slice(1).map((p) => Number(p.split(':')[1])).join(' ')
  }
  return out
}

const eng = readFileSync(engPath, 'utf8')
const org = readFileSync(orgPath, 'utf8')
const engCounts = counts(eng)
const orgCounts = counts(org)

// "PSA 51:0 = PSA 51:1" + "PSA 51:0 = PSA 51:2" → one rule PSA 51:0 → 51:1-2
const rules = []
for (const line of eng.split('\n')) {
  const m = /^([1-3A-Z]{3}) (\d+):(\d+)(?:-(\d+))? = ([1-3A-Z]{3}) (\d+):(\d+)(?:-(\d+))?\s*$/.exec(line.trim())
  if (!m || !CANON.has(m[1])) continue
  if (m[1] !== m[5]) throw new Error(`cross-book rule: ${line}`)
  const from = `${m[1]} ${m[2]}:${m[3]}${m[4] ? `-${m[4]}` : ''}`
  const prev = rules[rules.length - 1]
  if (prev && prev.from === from) {
    const end = m[8] ?? m[7]
    prev.to = `${prev.to.replace(/-\d+$/, '')}-${end}`
    continue
  }
  rules.push({ from, to: `${m[5]} ${m[6]}:${m[7]}${m[8] ? `-${m[8]}` : ''}` })
}

const notice = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'LICENSE-libpalaso.txt'), 'utf8')
const q = (s) => `'${s}'`
const src = `/*! Versification data derived from eng.vrs / org.vrs of SIL libpalaso
 * (https://github.com/sillsdev/libpalaso, SIL.Scripture/Resources), used
 * under the MIT licence:
 *
${notice
  .trim()
  .split('\n')
  .map((l) => ` * ${l}`.trimEnd())
  .join('\n')}
 */
// GENERATED by tools/versification/build-data.mjs — do not edit by hand.

/** Verses per chapter in English versification (eng.vrs), space-separated. */
export const ENG_VERSES: Readonly<Record<string, string>> = {
${Object.entries(engCounts)
  .map(([b, c]) => `  ${/^\d/.test(b) ? q(b) : b}: '${c}',`)
  .join('\n')}
}

/** Verses per chapter in original (Hebrew/Greek) versification (org.vrs),
 * for the books where it differs from ENG_VERSES. */
export const ORG_VERSES: Readonly<Record<string, string>> = {
${Object.entries(orgCounts)
  .filter(([b, c]) => engCounts[b] !== c)
  .map(([b, c]) => `  ${/^\d/.test(b) ? q(b) : b}: '${c}',`)
  .join('\n')}
}

/** English → original. Verses not covered map to the same number. Verse 0
 * = an English psalm title, which has no number of its own. */
export const ENG_TO_ORG: readonly { from: string; to: string }[] = [
${rules.map((r) => `  { from: '${r.from}', to: '${r.to}' },`).join('\n')}
]
`
writeFileSync(OUT, src)
process.stderr.write(`wrote ${OUT}: ${rules.length} rules\n`)
